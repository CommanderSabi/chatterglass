"""Bug report assembly.

Consent-first, exactly like Horidoro: nothing this builds leaves the machine
until the user presses Copy, Save or Open issue. Only environment facts — never
chat URLs, channel names or tokens.
"""

from __future__ import annotations

import os
import platform
import re
from typing import List, Optional

BANNER = ("<!-- Chatterglass bug report. Generated by the app; review before "
          "posting. -->")

# Same defence as Horidoro: a bug report is text an AI may read, so it must not be
# able to carry instructions. Strip escape sequences, control and bidi characters,
# markdown fences, and lines that look like prompt injection.
_ANSI_ESC = re.compile(r"\x1b\[[0-9;?]*[ -/]*[@-~]")
_CTRL_CHARS = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f\u200b-\u200f"
                         r"\u202a-\u202e\u2066-\u2069\ufeff]")
_INJECTION_LINE = re.compile(
    r"ignore\s+(all\s+|any\s+|previous\s+)?instructions"
    r"|system\s+prompt|reveal\s+(your|the)\s+(system\s+)?(prompt|instructions)"
    r"|you\s+are\s+(now\s+)?(an?\s+)?(ai|assistant|chatbot|language\s+model)"
    r"|<\|im_(start|end)\|>|developer\s+mode|dev\s*mode"
    r"|###\s*(system|instruction|user)\b", re.IGNORECASE)


def sanitize(text: str, max_line: int = 400, max_total: int = 12000) -> str:
    """Clean report text so it cannot smuggle instructions to an AI reader."""
    out = []
    for raw in str(text).splitlines():
        line = _ANSI_ESC.sub("", raw)
        line = _CTRL_CHARS.sub("", line)
        line = line.replace("`", "'")
        line = line.rstrip()
        if not line:
            continue
        if _INJECTION_LINE.search(line):
            continue
        if len(line) > max_line:
            line = line[:max_line] + "\u2026"
        out.append(line)
    joined = _redact("\n".join(out)).strip("\n")
    if len(joined) > max_total:
        joined = joined[:max_total] + "\n\u2026(truncated)"
    return joined


def _redact(text: str) -> str:
    home = os.path.expanduser("~")
    text = text.replace(home, "~")
    user = os.environ.get("USER") or ""
    if user:
        text = re.sub(r"\b%s\b" % re.escape(user), "<user>", text)
    # Chat overlay URLs can contain usernames; keep the host, drop the query.
    text = re.sub(r"(https?://[^\s?]+)\?[^\s]*", r"\1?<redacted>", text)
    return text


def _os_release() -> str:
    """Prefer PRETTY_NAME; fall back to ID + VERSION_ID."""
    values = {}
    try:
        with open("/etc/os-release", "r", encoding="utf-8") as handle:
            for line in handle:
                if "=" in line:
                    key, _, value = line.strip().partition("=")
                    values[key] = value.strip().strip('"')
    except OSError:
        return platform.platform()
    if values.get("PRETTY_NAME"):
        return values["PRETTY_NAME"]
    if values.get("ID"):
        return "%s %s" % (values["ID"], values.get("VERSION_ID", "")).strip()
    return platform.platform()


def build_report(app=None, extra: str = "") -> str:
    """Environment facts only. No tokens, no channel names, no overlay URLs."""
    lines: List[str] = [BANNER, "", "## Environment"]

    from . import __version__, layer

    lines.append("Chatterglass: %s" % __version__)
    lines.append("OS: %s" % _os_release())
    lines.append("Kernel: %s" % platform.release())
    lines.append("Session: %s / %s" % (os.environ.get("XDG_SESSION_TYPE", "?"),
                                       os.environ.get("XDG_CURRENT_DESKTOP", "?")))
    lines.append("Python: %s" % platform.python_version())

    try:
        import gi
        gi.require_version("Gtk", "3.0")
        gi.require_version("WebKit2", "4.1")
        from gi.repository import Gtk, WebKit2
        lines.append("GTK: %d.%d.%d" % (Gtk.get_major_version(),
                                        Gtk.get_minor_version(),
                                        Gtk.get_micro_version()))
        lines.append("WebKitGTK: %d.%d.%d" % (WebKit2.get_major_version(),
                                              WebKit2.get_minor_version(),
                                              WebKit2.get_micro_version()))
    except Exception as error:  # noqa: BLE001
        lines.append("GTK/WebKit: unavailable (%s)" % error)

    try:
        lines.append("Layer shell: %s" % ("supported" if layer.supported()
                                          else "NOT supported"))
    except Exception:  # noqa: BLE001
        lines.append("Layer shell: unknown")

    try:
        from . import install_state
        lines.append("Install state: %s" % ("installed" if install_state.is_installed()
                                            else "not installed"))
        lines.append("Install path: %s" % install_state.INSTALL_DIR)
        lines.append("Installed version: %s" % (install_state.installed_version() or "-"))
    except Exception as error:  # noqa: BLE001
        lines.append("Install state: unknown (%s)" % error)

    if app is not None:
        status, detail = getattr(app, "discord_status", ("unknown", ""))
        lines.append("Discord: %s%s" % (status, (" — " + detail) if detail else ""))
        slots = getattr(app.config, "slots", [])
        lines.append("Overlays: %d" % len(slots))
        for slot in slots:
            # kind and geometry only: no names, no URLs
            lines.append("  - %s %dx%d visible=%s click_through=%s"
                         % (slot.kind, slot.width, slot.height,
                            slot.visible, slot.click_through))

    if extra.strip():
        lines += ["", "## What happened", extra.strip()]

    return sanitize("\n".join(lines)) + "\n"
