#!/usr/bin/env python3
"""Regenerate chatterglass/_assets.py from the loose asset files.

The single-file build needs the HTML, CSS and JS inside the program, because a
zipapp cannot open files that sit next to the module. Run this after editing
panel.html, style.css or backdrop.js.
"""

from __future__ import annotations

import base64
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, "chatterglass")
TEXT_ASSETS = {"PANEL_HTML": "panel.html", "STYLE_CSS": "style.css",
               "BACKDROP_JS": "backdrop.js"}
ICON_SIZES = (32, 48, 64, 128, 256, 512)


def main() -> int:
    lines = ['"""Generated by make_assets.py — do not edit by hand."""', "",
             "from __future__ import annotations", ""]
    for constant, filename in TEXT_ASSETS.items():
        with open(os.path.join(PKG, filename), "r", encoding="utf-8") as handle:
            content = handle.read()
        lines.append("%s = %r" % (constant, content))
        lines.append("")

    lines.append("ICONS = {")
    for size in ICON_SIZES:
        path = os.path.join(HERE, "icons", "chatterglass-%d.png" % size)
        if not os.path.exists(path):
            continue
        with open(path, "rb") as handle:
            encoded = base64.b64encode(handle.read()).decode("ascii")
        lines.append("    %d: %r," % (size, encoded))
    lines.append("}")
    lines.append("")

    target = os.path.join(PKG, "_assets.py")
    with open(target, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))

    size = os.path.getsize(target)
    print("wrote %s (%.1f KiB)" % (target, size / 1024))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
